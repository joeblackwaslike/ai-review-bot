import {
	ENV_ALIASES,
	envNameForPath,
	listSchemaLeaves,
	type SecretSpec,
	SHARED_WEBHOOK_SECRET,
	secretSpecs,
	type ZodNode,
} from "./env.js";
import { isLivePath } from "./live.js";
import { ConfigSchema } from "./schema.js";

export const DOCS_START = "<!-- config-reference:start -->";
export const DOCS_END = "<!-- config-reference:end -->";

export interface DocRow {
	path: string;
	env: string;
	alias: string;
	type: string;
	default: string;
	live: boolean;
	description: string;
}

const aliasByPath = new Map(
	Object.entries(ENV_ALIASES).flatMap(([name, entry]) =>
		entry.paths.map((path) => [
			path.join("."),
			`${name} (${entry.deprecated ? "deprecated" : "permanent"})`,
		]),
	),
);

export function buildConfigRows(): DocRow[] {
	return listSchemaLeaves(ConfigSchema as unknown as ZodNode).map((leaf) => {
		const dotted = leaf.path.join(".");
		return {
			path: dotted,
			env:
				leaf.path[0] === "models" || leaf.kind === undefined
					? "none"
					: envNameForPath(leaf.path),
			alias: aliasByPath.get(dotted) ?? "none",
			type: leaf.type,
			default: leaf.default,
			live: isLivePath(leaf.path),
			description: leaf.description,
		};
	});
}

function secretDocRows(): {
	envName: string;
	alias: string;
	permanence: string;
}[] {
	const specs: SecretSpec[] = secretSpecs({
		reviewers: { claude: {}, codex: {} },
	} as never);
	return [
		...specs.filter((s) => s !== SHARED_WEBHOOK_SECRET),
		SHARED_WEBHOOK_SECRET,
	].map((spec) => {
		const alias = spec.aliases[0];
		return {
			envName: spec.envName,
			alias: alias ? `\`${alias.name}\`` : "none",
			permanence: alias ? (alias.deprecated ? "deprecated" : "permanent") : "-",
		};
	});
}

const cell = (text: string): string => text.replaceAll("|", "\\|");

export function renderConfigSection(): string {
	const lines = [
		DOCS_START,
		"## Config reference",
		"",
		"Generated by `pnpm docs:config` from `src/config/schema.ts`. Do not edit by hand.",
		"",
		"Values come from `.ai-review.yaml`. Any supported scalar leaf can be overridden by an environment variable named `AI_REVIEW_` plus the path in upper snake case, with `__` between segments (`review.delaySeconds` becomes `AI_REVIEW_REVIEW__DELAY_SECONDS`). A deprecated alias works but logs a warning; when both are set the derived name wins. An unknown `AI_REVIEW_*` variable is a hard error.",
		"",
		"Env overrides apply to every section. Dynamic map entries must already exist in the YAML before an env var can set them: `reviewers.<id>`, `reviewers.<id>.skills.<skill>` and `providers.<provider>`. `version` and everything under `models` have no env var. Array leaves take a JSON value. In `<ID>`, `<SKILL>` and `<PROVIDER>`, hyphens become underscores.",
		"",
		"Rows marked Live can also be overridden at runtime through Edge Config (`EDGE_CONFIG`, package `@vercel/global-config`) using the same env names as keys, with no redeploy. Edge Config can disable but cannot enable, so an Edge `true` over a disabled `review.enabled`, `reviewers.<id>.enabled` or `roles.verifier.enabled` is ignored and listed under `edge.ignored` in `/api/debug`.",
		"",
		"| YAML path | Env var | Alias | Type | Default | Live | Description |",
		"| --- | --- | --- | --- | --- | --- | --- |",
	];
	for (const r of buildConfigRows()) {
		const code = (t: string) => (t === "none" ? t : `\`${t}\``);
		const [aliasName, aliasKind] = r.alias.split(" ");
		const alias = aliasKind
			? `${code(aliasName as string)} ${aliasKind}`
			: "none";
		const dflt =
			r.default === "required" || r.default === "unset"
				? r.default
				: `\`${cell(r.default)}\``;
		lines.push(
			`| \`${r.path}\` | ${code(r.env)} | ${alias} | ${cell(r.type)} | ${dflt} | ${r.live ? "yes" : ""} | ${cell(r.description)} |`,
		);
	}
	lines.push(
		"",
		"### Secrets",
		"",
		"Secrets are never part of the config tree. Each is read from the env var below, or from a standard name. When both are set the env var named `AI_REVIEW_` plus the path wins. Only `GITHUB_APP_ID`, `GITHUB_APP_PRIVATE_KEY` and the standard provider key names (`ANTHROPIC_API_KEY`, `OPENAI_API_KEY`, `GOOGLE_GENERATIVE_AI_API_KEY`) are permanent aliases. Every other standard name, including `GITHUB_WEBHOOK_SECRET`, is deprecated and logs a warning. Any other reviewer uses `AI_REVIEW_REVIEWERS__<ID>__PRIVATE_KEY` and `AI_REVIEW_REVIEWERS__<ID>__WEBHOOK_SECRET`; a name for a reviewer that is not in the YAML is ignored with a warning.",
		"",
		"| Env var | Standard name | Permanence |",
		"| --- | --- | --- |",
		...secretDocRows().map(
			(r) => `| \`${r.envName}\` | ${r.alias} | ${r.permanence} |`,
		),
		"",
		DOCS_END,
	);
	return lines.join("\n");
}

export function injectConfigSection(doc: string, section: string): string {
	const start = doc.indexOf(DOCS_START);
	if (start === -1) {
		if (doc.includes(DOCS_END)) {
			throw new Error(`docs/configuration.md is missing ${DOCS_START}`);
		}
		return `${doc.trimEnd()}\n\n${section}\n`;
	}
	const end = doc.indexOf(DOCS_END, start);
	if (end === -1) {
		throw new Error(
			doc.includes(DOCS_END)
				? `docs/configuration.md has ${DOCS_END} before ${DOCS_START}`
				: `docs/configuration.md is missing ${DOCS_END}`,
		);
	}
	return doc.slice(0, start) + section + doc.slice(end + DOCS_END.length);
}
