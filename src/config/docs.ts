import { z } from "zod";
import { ENV_ALIASES, envNameForPath, unwrap, type ZodNode } from "./env.js";
import { ConfigSchema } from "./schema.js";

export const DOCS_START = "<!-- config-reference:start -->";
export const DOCS_END = "<!-- config-reference:end -->";

export interface DocRow {
	path: string;
	env: string;
	alias: string;
	type: string;
	default: string;
	description: string;
}

interface Def {
	type: string;
	innerType?: ZodNode;
	valueType?: ZodNode;
	element?: ZodNode;
	entries?: Record<string, unknown>;
	values?: unknown[];
	defaultValue?: unknown;
}

const defOf = (node: ZodNode): Def => node._zod.def as Def;

const MAP_KEYS: Record<string, string> = {
	models: "<provider/model>",
	reviewers: "<id>",
};

function wrapperChain(node: ZodNode): ZodNode[] {
	const chain = [node];
	let current = node;
	while (defOf(current).innerType) {
		current = defOf(current).innerType as ZodNode;
		chain.push(current);
	}
	return chain;
}

function describeOf(node: ZodNode): string {
	for (const n of wrapperChain(node)) {
		const text = z.globalRegistry.get(n as never)?.description;
		if (text) return text;
	}
	return "";
}

function typeOf(node: ZodNode): string {
	const def = defOf(unwrap(node));
	if (def.type === "enum")
		return `one of ${Object.keys(def.entries ?? {}).join(", ")}`;
	if (def.type === "array") return `${typeOf(def.element as ZodNode)}[]`;
	return def.type;
}

function defaultOf(node: ZodNode): string {
	const wrapper = wrapperChain(node).find((n) => defOf(n).type === "default");
	if (wrapper) return JSON.stringify(defOf(wrapper).defaultValue);
	return wrapperChain(node).some((n) => defOf(n).type === "optional")
		? "unset"
		: "required";
}

const aliasByPath = new Map(
	Object.entries(ENV_ALIASES).map(([name, entry]) => [
		entry.path.join("."),
		`${name} (${entry.deprecated ? "deprecated" : "permanent"})`,
	]),
);

function walk(node: ZodNode, path: string[], out: DocRow[]): void {
	const inner = unwrap(node);
	const def = defOf(inner);
	if (def.type === "object" && inner.shape) {
		for (const [key, child] of Object.entries(inner.shape)) {
			walk(child, [...path, key], out);
		}
		return;
	}
	if (def.type === "record") {
		walk(
			def.valueType as ZodNode,
			[...path, MAP_KEYS[path[0] as string] ?? "<key>"],
			out,
		);
		return;
	}
	const dotted = path.join(".");
	out.push({
		path: dotted,
		env:
			path[0] === "models" || typeOf(node) === "literal"
				? "none"
				: envNameForPath(path),
		alias: aliasByPath.get(dotted) ?? "none",
		type: typeOf(node),
		default: defaultOf(node),
		description: describeOf(node),
	});
}

export function buildConfigRows(): DocRow[] {
	const rows: DocRow[] = [];
	walk(ConfigSchema as unknown as ZodNode, [], rows);
	return rows;
}

const cell = (text: string): string => text.replaceAll("|", "\\|");

export function renderConfigSection(): string {
	const lines = [
		DOCS_START,
		"## Config reference",
		"",
		"Generated by `pnpm docs:config` from `src/config/schema.ts`. Do not edit by hand.",
		"",
		"Values come from `config/ai-review.yaml`. Any scalar leaf can be overridden by an environment variable named `AI_REVIEW_` plus the path in upper snake case, with `__` between segments (`review.delaySeconds` becomes `AI_REVIEW_REVIEW__DELAY_SECONDS`). A deprecated alias works but logs a warning; when both are set the derived name wins. An unknown `AI_REVIEW_*` variable is a hard error.",
		"",
		"Env overrides apply only to `reviewers.<id>` entries already present in the YAML. `models` entries have no env var. Array leaves take a JSON value. In `<ID>`, hyphens in a reviewer id become underscores.",
		"",
		"| YAML path | Env var | Alias | Type | Default | Description |",
		"| --- | --- | --- | --- | --- | --- |",
	];
	for (const r of buildConfigRows()) {
		const code = (t: string) => (t === "none" ? t : `\`${t}\``);
		const [aliasName, aliasKind] = r.alias.split(" ");
		const alias = aliasKind
			? `${code(aliasName as string)} ${aliasKind}`
			: "none";
		const dflt =
			r.default === "required" || r.default === "unset"
				? r.default
				: `\`${cell(r.default)}\``;
		lines.push(
			`| \`${r.path}\` | ${code(r.env)} | ${alias} | ${cell(r.type)} | ${dflt} | ${cell(r.description)} |`,
		);
	}
	lines.push("", DOCS_END);
	return lines.join("\n");
}

export function injectConfigSection(doc: string, section: string): string {
	const start = doc.indexOf(DOCS_START);
	const end = doc.indexOf(DOCS_END);
	if (start === -1 || end === -1) return `${doc.trimEnd()}\n\n${section}\n`;
	return doc.slice(0, start) + section + doc.slice(end + DOCS_END.length);
}
